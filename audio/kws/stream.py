"""Streaming ONNX wake-word inference for skull-assistant integration.

The adapter consumes mono PCM at 16 kHz, evaluates a one-second window every 100 ms,
smooths keyword probabilities and emits a refractory-limited event dictionary.
"""

from __future__ import annotations

import json
from collections import deque
from pathlib import Path
from typing import Callable, Dict, List, Optional

import numpy as np
import torch

from .features import LogMel

SAMPLE_RATE = 16000


class WakeWordStreamer:
    def __init__(self, onnx_path: str, run_path: str, calib_path: str, keyword: str,
                 threshold: float = 0.5, hop_ms: int = 100, smooth_windows: int = 3,
                 refractory_s: float = 1.0, session=None,
                 feature_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None):
        self.meta = json.loads(Path(run_path).read_text())
        self.keyword = keyword
        self.keyword_index = self.meta["classes"].index(keyword)
        self.model_name = self.meta["name"]
        self.threshold = threshold
        self.hop_samples = SAMPLE_RATE * hop_ms // 1000
        self.window_samples = SAMPLE_RATE
        self.refractory_s = refractory_s
        if smooth_windows < 1:
            raise ValueError("smooth_windows must be positive")
        if session is None:
            import onnxruntime as ort
            session = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])
        self.session = session
        self.input_name = session.get_inputs()[0].name
        calib = np.load(calib_path)
        self.mean, self.std = float(calib["mean"]), float(calib["std"])
        self.feature_fn = feature_fn
        self.logmel = None if feature_fn is not None else LogMel()
        self.buffer = np.empty(0, dtype=np.float32)
        self.total_samples = 0
        self.next_eval_sample = self.window_samples
        self.history = deque(maxlen=smooth_windows)
        self.next_event_time = 0.0

    def reset(self) -> None:
        self.buffer = np.empty(0, dtype=np.float32)
        self.total_samples = 0
        self.next_eval_sample = self.window_samples
        self.history.clear()
        self.next_event_time = 0.0

    def _features(self, window: np.ndarray) -> np.ndarray:
        if self.feature_fn is not None:
            x = self.feature_fn(window)
        else:
            with torch.no_grad():
                x = self.logmel(torch.from_numpy(window).unsqueeze(0))[0].numpy()
        x = (np.asarray(x, dtype=np.float32) - self.mean) / self.std
        return x[None, None]

    def _probability(self, window: np.ndarray) -> float:
        logits = self.session.run(None, {self.input_name: self._features(window)})[0][0]
        logits = np.asarray(logits, dtype=np.float32)
        probs = np.exp(logits - logits.max())
        probs /= probs.sum()
        return float(probs[self.keyword_index])

    def accept_pcm(self, pcm) -> List[Dict[str, object]]:
        """Accept arbitrary PCM chunks and return wake events generated by this chunk."""
        if isinstance(pcm, (bytes, bytearray, memoryview)):
            x = np.frombuffer(pcm, dtype=np.int16).astype(np.float32) / 32768.0
        else:
            raw = np.asarray(pcm)
            if raw.ndim != 1:
                raise ValueError("PCM input must be mono, one-dimensional")
            if raw.dtype == np.int16:
                x = raw.astype(np.float32) / 32768.0
            elif np.issubdtype(raw.dtype, np.floating):
                x = np.clip(raw.astype(np.float32), -1.0, 1.0)
            else:
                raise ValueError("PCM input must be int16, float or int16 bytes")
        events = []
        for start in range(0, len(x), self.hop_samples):
            piece = x[start:start + self.hop_samples]
            self.buffer = np.concatenate([self.buffer, piece])[-self.window_samples:]
            self.total_samples += len(piece)
            if len(self.buffer) < self.window_samples or self.total_samples < self.next_eval_sample:
                continue
            window_end = len(self.buffer) - (self.total_samples - self.next_eval_sample)
            window = self.buffer[window_end - self.window_samples:window_end]
            self.history.append(self._probability(window))
            now = self.next_eval_sample / SAMPLE_RATE
            self.next_eval_sample += self.hop_samples
            if len(self.history) < self.history.maxlen:
                continue
            confidence = float(np.mean(self.history))
            if confidence >= self.threshold and now >= self.next_event_time:
                events.append({"event": "wake", "word": self.keyword, "confidence": confidence,
                               "time_s": now, "model": self.model_name})
                self.next_event_time = now + self.refractory_s
                self.history.clear()
        return events
