"""Test vector for the on-device front-end: one WAV as a C array of int16 PCM plus the
reference log-mel features (before and after normalisation) computed by features.py, so
the firmware can run the same PCM through its own pipeline and the two can be diffed.

    python audio/kws/export_testvector.py --wav data/speech_commands_v2/yes/<clip>.wav --out export/testvector

Writes
    <out>.h        const int16_t tv_pcm[16000]; const float tv_logmel[49*40]; const float tv_norm[49*40];
                   plus TV_FRAMES, TV_MELS, TV_MEAN, TV_STD
    <out>.npz      the same arrays for Python-side comparison
    <out>_mel_fb.h sparse mel filterbank (start bin, length, weights per band) and the Hann window,
                   exported from features.py so the firmware uses identical coefficients
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from audio.kws.cache import fit_length, read_wav  # noqa: E402
from audio.kws.features import LogMel  # noqa: E402


def c_array(name: str, ctype: str, values: np.ndarray, per_line: int = 12, fmt: str = "{}") -> str:
    vals = [fmt.format(v) for v in values.ravel().tolist()]
    rows = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"const {ctype} {name}[{values.size}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--wav", required=True)
    p.add_argument("--cache", default=str(ROOT / "data" / "kws_cache"), help="for mean/std (index.json)")
    p.add_argument("--out", default=str(ROOT / "export" / "testvector"))
    a = p.parse_args()

    pcm = fit_length(read_wav(Path(a.wav)))
    fe = LogMel()
    with torch.no_grad():
        logmel = fe(torch.from_numpy(pcm)[None])[0].numpy()  # (49, 40)
    index = json.loads((Path(a.cache) / "index.json").read_text())
    mean, std = float(index["mean"]), float(index["std"])
    norm = (logmel - mean) / std
    pcm_i16 = np.clip(np.round(pcm * 32768.0), -32768, 32767).astype(np.int16)

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    frames, mels = logmel.shape
    header = (f"// generated by audio/kws/export_testvector.py from {Path(a.wav).name}\n"
              f"#pragma once\n#include <stdint.h>\n#define TV_SAMPLES {pcm_i16.size}\n#define TV_FRAMES {frames}\n"
              f"#define TV_MELS {mels}\n#define TV_MEAN ({mean:.6f}f)\n#define TV_STD ({std:.6f}f)\n\n")
    body = (c_array("tv_pcm", "int16_t", pcm_i16, 16)
            + c_array("tv_logmel", "float", logmel.astype(np.float32), 8, "{:.6f}f")
            + c_array("tv_norm", "float", norm.astype(np.float32), 8, "{:.6f}f"))
    out.with_suffix(".h").write_text(header + body)
    np.savez(out.with_suffix(".npz"), pcm=pcm_i16, logmel=logmel.astype(np.float32), norm=norm.astype(np.float32),
             mean=np.float32(mean), std=np.float32(std))

    # Sparse mel filterbank + window, identical to features.py.
    fb = fe.fb.numpy()  # (40, 257)
    starts, lengths, weights = [], [], []
    for band in fb:
        nz = np.flatnonzero(band > 0)
        if nz.size == 0:
            starts.append(0)
            lengths.append(0)
            continue
        starts.append(int(nz[0]))
        lengths.append(int(nz[-1] - nz[0] + 1))
        weights.extend(band[nz[0]:nz[-1] + 1].tolist())
    fb_h = (f"// mel filterbank and window from audio/kws/features.py: sr=16000 n_fft={fe.n_fft} "
            f"win={fe.win_length} hop={fe.hop_length} n_mels={fb.shape[0]} bins={fb.shape[1]}\n"
            f"#pragma once\n#include <stdint.h>\n#define MEL_BANDS {fb.shape[0]}\n#define FFT_BINS {fb.shape[1]}\n"
            f"#define WIN_LENGTH {fe.win_length}\n#define HOP_LENGTH {fe.hop_length}\n#define N_FFT {fe.n_fft}\n"
            f"#define LOG_EPS ({fe.eps:g}f)\n\n"
            + c_array("mel_start", "uint16_t", np.array(starts), 16)
            + c_array("mel_len", "uint16_t", np.array(lengths), 16)
            + c_array("mel_weight", "float", np.array(weights, dtype=np.float32), 8, "{:.7f}f")
            + c_array("hann_window", "float", fe.window.numpy().astype(np.float32), 8, "{:.7f}f"))
    (out.parent / (out.name + "_mel_fb.h")).write_text(fb_h)
    print(f"wrote {out.with_suffix('.h')} ({pcm_i16.size} samples, {frames}x{mels} features), "
          f"{out.parent / (out.name + '_mel_fb.h')} ({len(weights)} mel weights)")


if __name__ == "__main__":
    main()
